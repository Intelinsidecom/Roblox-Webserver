        private async Task LoadPlaceDataAsync()
        {
            try
            {
                IsEnabled = false;
                _currentPlace = await _metadataRepo.GetAssetByIdAsync(_connectionString, _placeId);

                if (_currentPlace == null)
                {
                    MessageBox.Show($"Asset with ID {_placeId} not found.", "Not Found",
                        MessageBoxButton.OK, MessageBoxImage.Warning);
                    Close();
                    return;
                }

                Title = $"Configure Place - {_currentPlace.Name} (ID: {_currentPlace.AssetId})";

                if (!_currentPlace.IsPlace)
                {
                    MessageBox.Show($"Asset ID {_placeId} is not a place. Editing has been disabled.",
                        "Not a Place", MessageBoxButton.OK, MessageBoxImage.Warning);
                }

                var universeId = await GamesRepository.GetUniverseIdFromPlaceIdAsync(_connectionString, _placeId);
                if (universeId.HasValue)
                {
                    _universeId = universeId.Value;
                }

                UpdateUIWithPlaceData();
                InitThumbnailRadioState();
                ThumbnailGalleryListBox.Visibility = ThumbnailAutoRadio.IsChecked == true ? Visibility.Collapsed : Visibility.Visible;
                await Task.WhenAll(
                    LoadGameIconAsync(),
                    LoadThumbnailsAsync(),
                    LoadDeveloperProductsAsync()
                );
            }
            catch (Exception ex)
            {
                MessageBox.Show($"Error loading place data: {ex.Message}", "Error",
                    MessageBoxButton.OK, MessageBoxImage.Error);
                Close();
            }
            finally
            {
                IsEnabled = true;
            }
        }

        private void UpdateUIWithPlaceData()
        {
            if (_currentPlace == null) return;

            var isPlace = _currentPlace.IsPlace;

            PlaceNameTextBox.Text = _currentPlace.Name ?? "";
            PlaceDescriptionTextBox.Text = _currentPlace.Description ?? "";
            SetGenreSelection(_currentPlace.Genre);

            SetDeviceCompatibility(_currentPlace.DeviceCompatibility);

            SellGameAccessCheckBox.IsChecked = _currentPlace.PaidAccessEnabled;
            PriceTextBox.Text = _currentPlace.PaidAccessPrice > 0 ? _currentPlace.PaidAccessPrice.ToString() : "";
            PricingPanel.IsEnabled = _currentPlace.PaidAccessEnabled;

            SetMaxPlayersSelection(_currentPlace.MaxVisitorCount);
            SetServerFillType(_currentPlace.ServerFillType);
            SetAccessType(_currentPlace.AccessType);

            AllowPrivateServersCheckBox.IsChecked = _currentPlace.PrivateServersAllowed;
            PrivateServerDetails.IsEnabled = _currentPlace.PrivateServersAllowed;
            if (_currentPlace.IsPrivateServersFree)
                PrivateServerFreeRadio.IsChecked = true;
            else
            {
                PrivateServerPaidRadio.IsChecked = true;
                PrivateServerPriceTextBox.Text = _currentPlace.PrivateServersPrice.ToString();
                PrivateServerPricePanel.IsEnabled = true;
            }

            SetGearPermissions(_currentPlace.IsAllGenresAllowed, _currentPlace.AllowedGearTypes);
            AllowCopyingCheckBox.IsChecked = _currentPlace.IsCopyingAllowed;

            AllowCopyInGameCheckBox.IsChecked = _currentPlace.AllowPlaceToBeCopiedInGame;
            AllowUpdateInGameCheckBox.IsChecked = _currentPlace.AllowPlaceToBeUpdatedInGame;

            if (_universeId > 0)
            {
                var universeInfo = GamesRepository.GetUniverseAsync(_connectionString, _universeId)
                    .GetAwaiter().GetResult();
                if (universeInfo != null)
                {
                    GameLink.NavigateUri = new Uri($"http://localhost/games/{_universeId}/");
                    GameLink.Inlines.Clear();
                    GameLink.Inlines.Add(universeInfo.Name ?? $"Universe {_universeId}");
                }
            }

            if (!isPlace)
            {
                DisableEditing();
            }
        }

