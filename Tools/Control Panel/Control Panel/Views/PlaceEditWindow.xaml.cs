        private async void UploadIconButton_Click(object sender, RoutedEventArgs e)
        {
            if (string.IsNullOrWhiteSpace(_selectedIconPath))
            {
                MessageBox.Show("Please select an image first using the 'Select Image' button.", "No Image Selected", MessageBoxButton.OK, MessageBoxImage.Information);
                return;
            }
            try
            {
                UploadIconButton.IsEnabled = false;

                var baseUrl = Settings.Default.ThumbnailUrl;
                if (string.IsNullOrWhiteSpace(baseUrl))
                    baseUrl = $"http://{Settings.Default.WebsiteHost}:{Settings.Default.WebsitePort}";

                var fileBytes = File.ReadAllBytes(_selectedIconPath);
                var resizedBytes = PlaceThumbnail.ResizeImage(fileBytes, 110, 110);
                var fileHash = HashingUtilities.GenerateFileHash(resizedBytes);

                var iconDir = System.IO.Path.Combine(Settings.Default.AssetsDirectory, "place-icons");
                System.IO.Directory.CreateDirectory(iconDir);
                var localIconPath = System.IO.Path.Combine(iconDir, $"{fileHash}.png");
                File.WriteAllBytes(localIconPath, resizedBytes);

                var iconUrl = $"{baseUrl.TrimEnd('/')}/{fileHash}.png";

                await PlaceThumbnail.SetPlaceCustomIconAsync(_connectionString, _placeId, iconUrl, iconUrl, fileHash);

                var bitmap = new BitmapImage();
                bitmap.BeginInit();
                bitmap.UriSource = new Uri(localIconPath, UriKind.Absolute);
                bitmap.CacheOption = BitmapCacheOption.OnLoad;
                bitmap.EndInit();
                GameIconImage.Source = bitmap;

                _currentPlace = await _metadataRepo.GetAssetByIdAsync(_connectionString, _placeId);
                _selectedIconPath = null;
                SelectedImageIndicator.Text = "No file selected";
                MessageBox.Show("Icon uploaded successfully.", "Success", MessageBoxButton.OK, MessageBoxImage.Information);
            }
            catch (Exception ex)
            {
                MessageBox.Show($"Error uploading icon: {ex.Message}", "Upload Failed", MessageBoxButton.OK, MessageBoxImage.Error);
            }
            finally
            {
                UploadIconButton.IsEnabled = true;
            }
        }

