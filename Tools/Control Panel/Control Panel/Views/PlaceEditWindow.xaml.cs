        }

        private void ThumbnailGalleryListBox_Drop(object sender, DragEventArgs e)
        {
            var droppedItem = e.Data.GetData(typeof(ThumbnailItem)) as ThumbnailItem;
            if (droppedItem == null || dragSourceItem == null) return;

            var listBox = sender as ListBox;
            if (listBox == null) return;

            int oldIndex = thumbnailItems.IndexOf(dragSourceItem);
            if (oldIndex < 0) return;

            var dropPoint = e.GetPosition(listBox);
            var hitResult = System.Windows.Media.VisualTreeHelper.HitTest(listBox, dropPoint);
            if (hitResult == null) return;

            DependencyObject obj = hitResult.VisualHit;
            while (obj != null && !(obj is ListBoxItem))
            {
                obj = System.Windows.Media.VisualTreeHelper.GetParent(obj);
            }

            if (obj is ListBoxItem targetItem)
            {
                int newIndex = listBox.ItemContainerGenerator.IndexFromContainer(targetItem);
                if (newIndex >= 0 && newIndex < thumbnailItems.Count && newIndex != oldIndex)
                {
                    thumbnailItems.Move(oldIndex, newIndex);
                    UpdateMainPreview();
                }
            }

            dragSourceItem = null;
        }

        private void ThumbnailGalleryListBox_MouseLeftButtonUp(object sender, System.Windows.Input.MouseButtonEventArgs e)
        {
            var listBox = sender as ListBox;
            if (listBox?.SelectedItem is ThumbnailItem selected)
                ThumbnailPreviewImage.Source = selected.ImageSource;
        }

        private async void DeleteThumbnail_Click(object sender, RoutedEventArgs e)
        {
            if (!(sender is Button) || !((sender as Button).Tag is ThumbnailItem))
                return;
            var item = (ThumbnailItem)((Button)sender).Tag;
            if (item.Id <= 0)
            {
                thumbnailItems.Remove(item);
                UpdateMainPreview();
                return;
            }
            try
            {
                var removed = await PlaceThumbnail.RemoveThumbnailAsync(_connectionString, _placeId, item.Id);
                if (removed)
                {
                    thumbnailItems.Remove(item);
                    UpdateMainPreview();
                }
                else
                    MessageBox.Show("Failed to delete thumbnail from database.", "Error", MessageBoxButton.OK, MessageBoxImage.Error);
            }
            catch (Exception ex)
            {
                MessageBox.Show($"Error deleting thumbnail: {ex.Message}", "Error", MessageBoxButton.OK, MessageBoxImage.Error);
            }
        }

