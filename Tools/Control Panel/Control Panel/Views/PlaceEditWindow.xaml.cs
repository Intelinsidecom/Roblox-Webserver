        private BitmapImage LoadBitmapFromUrlOrLocal(string url)
        {
            if (string.IsNullOrWhiteSpace(url))
                return null;
            try
            {
                var bitmap = new BitmapImage();
                bitmap.BeginInit();
                bitmap.UriSource = new Uri(url);
                bitmap.CacheOption = BitmapCacheOption.OnLoad;
                bitmap.EndInit();
                if (bitmap.CanFreeze) bitmap.Freeze();
                return bitmap;
            }
            catch
            {
                try
                {
                    var fileName = url.Split('/').LastOrDefault();
                    if (!string.IsNullOrWhiteSpace(fileName))
                    {
                        var searchDirs = new[]
                        {
                            System.IO.Path.Combine(Settings.Default.AssetsDirectory, "place-icons"),
                            System.IO.Path.Combine(Settings.Default.AssetsDirectory, "place-thumbnails"),
                            System.IO.Path.Combine(Settings.Default.ThumbnailsOutputDirectory, "place-icons"),
                            System.IO.Path.Combine(Settings.Default.ThumbnailsOutputDirectory, "place-thumbnails"),
                        };
                        foreach (var dir in searchDirs)
                        {
                            var localPath = System.IO.Path.Combine(dir, fileName);
                            if (File.Exists(localPath))
                            {
                                var bitmap = new BitmapImage();
                                bitmap.BeginInit();
                                bitmap.UriSource = new Uri(localPath, UriKind.Absolute);
                                bitmap.CacheOption = BitmapCacheOption.OnLoad;
                                bitmap.EndInit();
                                if (bitmap.CanFreeze) bitmap.Freeze();
                                return bitmap;
                            }
                        }
                    }
                }
                catch (Exception ex) { Console.WriteLine($"[ERROR] LoadBitmapFromUrlOrLocal: {ex}"); }
                return null;
            }
        }

        private async Task LoadGameIconAsync()
        {
            try
            {
                bool hasCustom = _currentPlace?.CustomIcon == true && !string.IsNullOrWhiteSpace(_currentPlace?.PlaceCustomIconUrl);
                bool hasGenerated = _currentPlace?.GeneratedIcon == true && !string.IsNullOrWhiteSpace(_currentPlace?.PlaceGeneratedIconUrl);

                if (hasCustom)
                {
                    var bmp = LoadBitmapFromUrlOrLocal(_currentPlace.PlaceCustomIconUrl);
                    GameIconImage.Source = bmp;
                    IconImageRadio.IsChecked = true;
                    IconAutoGeneratedRadio.IsChecked = false;
                }
                else if (hasGenerated)
                {
                    var bmp = LoadBitmapFromUrlOrLocal(_currentPlace.PlaceGeneratedIconUrl);
                    GameIconImage.Source = bmp;
                    IconImageRadio.IsChecked = false;
                    IconAutoGeneratedRadio.IsChecked = true;
                }
                else
                {
                    GameIconImage.Source = null;
                    IconImageRadio.IsChecked = false;
                    IconAutoGeneratedRadio.IsChecked = false;
                }

                if (hasGenerated)
                {
                    var bmp = LoadBitmapFromUrlOrLocal(_currentPlace.PlaceGeneratedIconUrl);
                    AutoGeneratedIconImage.Source = bmp;
                }
                else
                {
                    AutoGeneratedIconImage.Source = null;
                }
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"Error loading game icon: {ex.Message}");
            }
        }

        private void InitThumbnailRadioState()
        {
            ThumbnailImageRadio.IsChecked = _currentPlace?.PlaceCustomThumbnail == true;
