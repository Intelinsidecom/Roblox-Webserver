        private void SetDeviceCompatibility(string deviceJson)
        {
            DeviceComputerCheckBox.IsChecked = false;
            DevicePhoneCheckBox.IsChecked = false;
            DeviceTabletCheckBox.IsChecked = false;
            DeviceConsoleCheckBox.IsChecked = false;

            if (string.IsNullOrWhiteSpace(deviceJson) || deviceJson == "[]") return;

            try
            {
                var ids = JsonSerializer.Deserialize<int[]>(deviceJson);
                if (ids == null) return;
                foreach (var id in ids)
                {
                    switch (id)
                    {
                        case 1: DeviceComputerCheckBox.IsChecked = true; break;
                        case 2: DeviceTabletCheckBox.IsChecked = true; break;
                        case 3: DevicePhoneCheckBox.IsChecked = true; break;
                        case 4: DeviceConsoleCheckBox.IsChecked = true; break;
                    }
                }
            }
            catch (Exception ex) { Console.WriteLine($"[ERROR] SetDeviceCompatibility: {ex}"); }
        }

