            {
                MessageBox.Show("Please select an image first using the 'Select Image' button.", "No Image Selected", MessageBoxButton.OK, MessageBoxImage.Information);
                return;
            }
            try
            {
                UploadThumbnailImageButton.IsEnabled = false;
                var baseUrl = Settings.Default.ThumbnailUrl;
                if (string.IsNullOrWhiteSpace(baseUrl))
                    baseUrl = $"http://{Settings.Default.WebsiteHost}:{Settings.Default.WebsitePort}";

                var fileBytes = File.ReadAllBytes(_selectedThumbnailPath);
                var resizedBytes = PlaceThumbnail.ResizeImage(fileBytes, 1280, 720);
                var fileHash = HashingUtilities.GenerateFileHash(resizedBytes);

                var thumbDir = System.IO.Path.Combine(Settings.Default.AssetsDirectory, "place-thumbnails");
