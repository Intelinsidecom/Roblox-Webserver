        }

        private async Task LoadThumbnailsAsync()
        {
            try
            {
                thumbnailItems.Clear();

                string autoGenUrl = _currentPlace?.PlaceGeneratedThumbnailUrl;
                bool hasAutoGen = ThumbnailAutoRadio.IsChecked == true && !string.IsNullOrWhiteSpace(autoGenUrl);

                if (!string.IsNullOrWhiteSpace(_currentPlace?.PlaceThumbnailVideo))
                {
                    ThumbnailVideoLinkTextBox.Text = _currentPlace.PlaceThumbnailVideo;
                }

                if (hasAutoGen)
                {
                    var bmp = LoadBitmapFromUrlOrLocal(autoGenUrl);
                    if (bmp != null)
                    {
                        thumbnailItems.Add(new ThumbnailItem { ImageSource = bmp });
                        AutoGeneratedThumbnailImage.Source = bmp;
                    }
                }
                else if (ThumbnailImageRadio.IsChecked == true)
                {
                    AutoGeneratedThumbnailImage.Source = null;
                    var entries = await PlaceThumbnail.GetPlaceImageThumbnailsAsync(_connectionString, _placeId);
                    foreach (var entry in entries)
                    {
                        var bmp = LoadBitmapFromUrlOrLocal(entry.Url);
                        if (bmp != null)
                            thumbnailItems.Add(new ThumbnailItem { Id = entry.Id, ImageSource = bmp });
                    }
                }
                else
                {
                    AutoGeneratedThumbnailImage.Source = null;
                }

                UpdateMainPreview();
            }
            catch (Exception ex)
            {
                System.Diagnostics.Debug.WriteLine($"Error loading thumbnails: {ex.Message}");
            }
        }

        private void UpdateMainPreview()
        {
            ThumbnailPreviewImage.Source = thumbnailItems.Count > 0 ? thumbnailItems[0].ImageSource : null;
        }

