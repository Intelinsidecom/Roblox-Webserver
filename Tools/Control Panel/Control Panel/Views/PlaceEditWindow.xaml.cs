        private void ThumbnailGalleryListBox_PreviewMouseMove(object sender, System.Windows.Input.MouseEventArgs e)
        {
            if (e.LeftButton == System.Windows.Input.MouseButtonState.Pressed)
            {
                var listBox = sender as ListBox;
                var item = listBox?.SelectedItem as ThumbnailItem;
                if (item != null)
                {
                    dragSourceItem = item;
                    DragDrop.DoDragDrop(listBox, item, DragDropEffects.Move);
                }
            }
        }

