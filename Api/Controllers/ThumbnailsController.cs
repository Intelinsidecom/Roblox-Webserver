using Microsoft.AspNetCore.Mvc;
using Microsoft.Extensions.Configuration;
using Common;
using Thumbnails;
using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;

namespace Api.Controllers
{
    public class BatchRequestEntry
    {
        public string requestId { get; set; } = string.Empty;
        public string type { get; set; } = string.Empty;
        public long targetId { get; set; }
        public string? size { get; set; }
    }

    [ApiController]
    [Route("v1")]
    public class ThumbnailsController : ControllerBase
    {
        private readonly IConfiguration _configuration;

        public ThumbnailsController(IConfiguration configuration)
        {
            _configuration = configuration;
        }

        /// <summary>
        /// POST /v1/batch
        /// Batch thumbnail lookup for multiple targets (avatars, headshots, game icons, assets, groups).
        /// Mirrors the Roblox thumbnails v1/batch endpoint.
        /// </summary>
        [HttpPost("batch")]
        public async Task<IActionResult> BatchThumbnails([FromBody] IEnumerable<BatchRequestEntry> request)
        {
            var thumbs = request?.ToList() ?? new List<BatchRequestEntry>();
            var connectionString = DatabaseUtilities.GetConnectionString(_configuration);

            var allResults = new List<object>();

            // Group by type and query each
            var groups = thumbs.GroupBy(t => t.type);

            foreach (var group in groups)
            {
                var type = group.Key;
                var entries = group.ToList();

                switch (type)
                {
                    case "Avatar":
                    case "AvatarThumbnail":
                        var avatarIds = entries.Select(e => e.targetId).Where(id => id > 0).Distinct().ToArray();
                        var avatars = await ThumbnailQueries.GetUserThumbnailUrlsAsync(connectionString, avatarIds);
                        foreach (var e in entries)
                        {
                            avatars.TryGetValue(e.targetId, out var imageUrl);
                            allResults.Add(BuildResult(e, imageUrl));
                        }
                        break;

                    case "AvatarHeadShot":
                    case "AvatarBust":
                        var headshotIds = entries.Select(e => e.targetId).Where(id => id > 0).Distinct().ToArray();
                        var headshots = await ThumbnailQueries.GetUserHeadshotUrlsAsync(connectionString, headshotIds);
                        foreach (var e in entries)
                        {
                            headshots.TryGetValue(e.targetId, out var imageUrl);
                            allResults.Add(BuildResult(e, imageUrl));
                        }
                        break;

                    case "GameIcon":
                    case "AutoGeneratedGameIcon":
                    case "ForceAutoGeneratedGameIcon":
                        var universeIds = entries.Select(e => e.targetId).Where(id => id > 0).Distinct().ToArray();
                        var icons = await UniverseThumbnailQueries.GetUniverseThumbnailUrlsAsync(connectionString, universeIds);
                        foreach (var e in entries)
                        {
                            icons.TryGetValue(e.targetId, out var imageUrl);
                            allResults.Add(BuildResult(e, imageUrl));
                        }
                        break;

                    case "GameThumbnail":
                    case "Asset":
                    case "AssetThumbnail":
                        var assetIds = entries.Select(e => e.targetId).Where(id => id > 0).Distinct().ToArray();
                        var assets = await ThumbnailQueries.GetAssetThumbnailUrlsAsync(connectionString, assetIds);
                        foreach (var e in entries)
                        {
                            assets.TryGetValue(e.targetId, out var imageUrl);
                            allResults.Add(BuildResult(e, imageUrl));
                        }
                        break;

                    case "AutoGeneratedAsset":
                    case "GroupIcon":
                        // No dedicated group_icon / place icon table in this schema; return error for each
                        foreach (var e in entries)
                        {
                            allResults.Add(new
                            {
                                requestId = e.requestId,
                                errorCode = 4,
                                errorMessage = "The requested Ids are invalid, of an invalid type or missing.",
                                targetId = e.targetId,
                                state = 1, // Error
                                imageUrl = (string?)null,
                                version = (string?)null
                            });
                        }
                        break;

                    default:
                        // Unknown type -> error for each
                        foreach (var e in entries)
                        {
                            allResults.Add(new
                            {
                                requestId = e.requestId,
                                errorCode = 4,
                                errorMessage = "The requested Ids are invalid, of an invalid type or missing.",
                                targetId = e.targetId,
                                state = 1, // Error
                                imageUrl = (string?)null,
                                version = (string?)null
                            });
                        }
                        break;
                }
            }

            return Ok(new { data = allResults });
        }

        private static object BuildResult(BatchRequestEntry entry, string? imageUrl)
        {
            if (string.IsNullOrEmpty(imageUrl))
            {
                return new
                {
                    requestId = entry.requestId,
                    errorCode = 4,
                    errorMessage = "The requested Ids are invalid, of an invalid type or missing.",
                    targetId = entry.targetId,
                    state = 1, // Error
                    imageUrl = (string?)null,
                    version = (string?)null
                };
            }

            return new
            {
                requestId = entry.requestId,
                errorCode = 0,
                errorMessage = string.Empty,
                targetId = entry.targetId,
                state = 2, // Completed
                imageUrl,
                version = "TN3"
            };
        }
    }
}
