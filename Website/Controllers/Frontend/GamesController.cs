        /// <summary>
        /// Get place media for thumbnail carousel (prioritizes custom thumbnails, falls back to auto-generated)
        /// </summary>
        private async Task<List<PlaceMedia>> GetPlaceMediaAsync(long rootPlaceId, string connectionString, CancellationToken cancellationToken = default)
        {
            var media = new List<PlaceMedia>();
            var customThumbnails = await Thumbnails.PlaceThumbnail.GetPlaceThumbnailsAsync(connectionString, rootPlaceId, cancellationToken);
            
            foreach (var thumbnail in customThumbnails)
            {
                var thumbnailType = thumbnail.GetType().GetProperty("type")?.GetValue(thumbnail)?.ToString();
                var url = thumbnail.GetType().GetProperty("url")?.GetValue(thumbnail)?.ToString();
                var videoUrl = thumbnail.GetType().GetProperty("videoUrl")?.GetValue(thumbnail)?.ToString();
                
                if (thumbnailType == "image" && !string.IsNullOrWhiteSpace(url))
                {
                    media.Add(new PlaceMedia
                    {
                        Type = "image",
                        Url = url,
                        IsVideo = false
                    });
                }
                else if (thumbnailType == "video" && !string.IsNullOrWhiteSpace(videoUrl))
                {
                    var thumbnailUrl = "";
                    
                    if (YouTubeUtilities.IsYouTubeUrl(videoUrl))
                    {
                        var videoId = YouTubeUtilities.ExtractVideoId(videoUrl);
                        if (!string.IsNullOrWhiteSpace(videoId))
                        {
                            thumbnailUrl = YouTubeUtilities.GetThumbnailUrl(videoId);
                        }
                    }
                    
                    media.Add(new PlaceMedia
                    {
                        Type = "video",
                        Url = videoUrl,
                        ThumbnailUrl = thumbnailUrl,
                        IsVideo = true
                    });
                }
            }
            
            if (media.Count == 0)
            {
                var assetRepo = new AssetMetadataRepository();
                var placeAsset = await assetRepo.GetPlaceByIdAsync(connectionString, rootPlaceId, cancellationToken);
                
                if (placeAsset != null)
                {
                    if (!string.IsNullOrWhiteSpace(placeAsset.PlaceGeneratedThumbnailUrl))
                    {
                        media.Add(new PlaceMedia
                        {
                            Type = "image",
                            Url = placeAsset.PlaceGeneratedThumbnailUrl,
                            IsVideo = false,
                            IsAutoGenerated = true
                        });
                    }
                    
                    if (placeAsset.PlaceVideoThumbnail && !string.IsNullOrWhiteSpace(placeAsset.PlaceThumbnailVideo))
                    {
                        var videoUrl = placeAsset.PlaceThumbnailVideo;
                        var thumbnailUrl = "";

                        if (YouTubeUtilities.IsYouTubeUrl(videoUrl))
                        {
                            var videoId = YouTubeUtilities.ExtractVideoId(videoUrl);
                            if (!string.IsNullOrWhiteSpace(videoId))
                            {
                                thumbnailUrl = YouTubeUtilities.GetThumbnailUrl(videoId);
                            }
                        }
                        
                        media.Add(new PlaceMedia
                        {
                            Type = "video",
                            Url = videoUrl,
                            ThumbnailUrl = thumbnailUrl,
                            IsVideo = true
                        });
                    }
                }
            }

            if (media.Count == 0)
            {
                media.Add(new PlaceMedia
                {
                    Type = "image",
                    Url = "/images/DefaultPlaceIcon.png",
                    IsVideo = false
                });
            }

            return media;
        }

        /// <summary>
        /// Returns the universe name page for a specific game/place
        /// </summary>
        [HttpGet("{id}/{name}")]
        [AllowAnonymous]
        public async Task<IActionResult> GetGameName(long id, string name, CancellationToken cancellationToken = default)
        {
            try
            {
                var connStr = _configuration.GetConnectionString("Default");
                var universeId = await GamesRepository.GetUniverseIdFromPlaceIdAsync(connStr, id, cancellationToken);
                if (!universeId.HasValue)
                {
                    return NotFound();
                }

                var universe = await GamesRepository.GetUniverseAsync(connStr, universeId.Value, cancellationToken);
                if (universe == null)
                {
                    return NotFound();
                }

                var description = await GamesRepository.GetPlaceDescriptionAsync(connStr, universe.RootPlaceId, cancellationToken);
                var placeThumbnails = await Thumbnails.PlaceThumbnail.GetPlaceThumbnailsAsync(connStr, universe.RootPlaceId, cancellationToken);
                var assetRepo = new AssetMetadataRepository();
                var placeAsset = await assetRepo.GetPlaceByIdAsync(connStr, universe.RootPlaceId, cancellationToken);
                var videoUrl = placeAsset?.PlaceVideoThumbnail == true ? placeAsset.PlaceThumbnailVideo : null;
                var autoGeneratedThumbnailUrl = placeAsset?.PlaceGeneratedThumbnailUrl;
                var userIdClaim = User.FindFirst(ClaimTypes.NameIdentifier)?.Value;
                long userId = 0;
                var isUserAuthenticated = !string.IsNullOrWhiteSpace(userIdClaim) && long.TryParse(userIdClaim, out userId) && userId > 0;
                bool isUserFavorite = false;
                int favoriteCount = 0;
                var assetsRepo = new Assets.AssetsRepository();
                
                if (isUserAuthenticated)
                {
                    isUserFavorite = await assetsRepo.UserHasFavoritedAsync(connStr, userId, id, cancellationToken);
                }
                
                favoriteCount = await assetsRepo.GetFavoriteCountAsync(connStr, id, cancellationToken);
                var creatorUserName = await UserQueries.GetUserNameByIdAsync(connStr, universe.CreatorUserId, cancellationToken)
                    .ConfigureAwait(false) ?? "Unknown";

                var votingService = new Games.VotingService(connStr);
                var (upVotes, downVotes) = await votingService.GetAssetVotesAsync(id, cancellationToken);
                bool? userVote = null;
                if (isUserAuthenticated)
                {
                    userVote = await votingService.GetUserVoteAsync(userId, id, cancellationToken);
                }

                var recommendedGames = await GamesQueries.GetRecommendedGamesAsync(7, connStr, cancellationToken);

                ViewBag.RecommendedGames = recommendedGames.Select(game => new
                {
                    PlaceId = game.PlaceId,
                    Name = game.Name,
                    CreatorName = game.CreatorName,
                    CreatorId = game.CreatorUserId,
                    PlayingCount = game.Playing,
                    ThumbnailUrl = game.IconUrl,
                    VoteUpCount = game.UpVotes,
                    VoteDownCount = game.DownVotes
                }).Cast<dynamic>().ToList();

                ViewBag.Id = id;
                ViewBag.Name = universe.Name;
                ViewBag.Description = description ?? string.Empty;
                ViewBag.CreatorUserId = universe.CreatorUserId;
                ViewBag.CreatorUserName = creatorUserName;
                ViewBag.UpVotes = upVotes;
                ViewBag.DownVotes = downVotes;
                ViewBag.UserVote = userVote;
                ViewBag.FavoriteCount = favoriteCount;
                ViewBag.IsUserAuthenticated = isUserAuthenticated;
                ViewBag.IsUserFavorite = isUserFavorite;
                ViewBag.PlaceThumbnails = placeThumbnails;
                ViewBag.VideoUrl = videoUrl;
                ViewBag.AutoGeneratedThumbnailUrl = autoGeneratedThumbnailUrl;
                
                var placeAdditionalData = await Assets.AssetsRepository.GetPlaceAdditionalDataAsync(connStr, universe.RootPlaceId, cancellationToken);
                if (placeAdditionalData.HasValue)
                {
                    ViewBag.CreatedAt = placeAdditionalData.Value.CreatedAt;
                    ViewBag.UpdatedAt = placeAdditionalData.Value.UpdatedAt;
                    ViewBag.MaxPlayers = placeAdditionalData.Value.MaxPlayers;
                    ViewBag.Genre = placeAdditionalData.Value.Genre;
                    ViewBag.IsAllGenresAllowed = placeAdditionalData.Value.IsAllGenresAllowed;
                    ViewBag.AllowedGearTypes = placeAdditionalData.Value.AllowedGearTypes;
                    ViewBag.PrivateServersAllowed = placeAdditionalData.Value.PrivateServersAllowed;
                    ViewBag.PrivateServersFree = placeAdditionalData.Value.PrivateServersFree;
                    ViewBag.PrivateServersPrice = placeAdditionalData.Value.PrivateServersPrice;
                }

                ViewBag.IsCopylocked = !(placeAsset?.IsCopyingAllowed ?? false);

                return View("~/Views/Pages/games/{id}/UniverseName.cshtml");
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Error loading game name for place ID {PlaceId}", id);
                return StatusCode(500);
            }
        }

