        /// <summary>
        /// Handles the "Create New Game" button from /develop. For now this immediately creates
        /// a universe and root place row in the database and then redirects user to a
        /// not-yet-implemented universe configuration page.
        /// </summary>
        [HttpGet("create")]
        public async Task<IActionResult> Create(CancellationToken cancellationToken)
        {
            var userIdClaim = User.FindFirst(ClaimTypes.NameIdentifier)?.Value;
            if (string.IsNullOrWhiteSpace(userIdClaim) || !long.TryParse(userIdClaim, out var userId) || userId <= 0)
            {
                return Redirect("/");
            }

            var connStr = _configuration.GetConnectionString("Default");
            var assetsRoot = _configuration["Assets:Directory"];
            var starterPlacePath = _configuration["Games:StarterPlacePath"];
            var enableCooldownRaw = _configuration["Games:EnableCreationCooldown"];
            var enableCooldown = true;
            if (!string.IsNullOrWhiteSpace(enableCooldownRaw) && bool.TryParse(enableCooldownRaw, out var parsedCooldown))
            {
                enableCooldown = parsedCooldown;
            }
            UniverseInfo universe;
            try
            {
                var creatorUserName = await UserQueries.GetUserNameByIdAsync(connStr, userId, cancellationToken)
                    .ConfigureAwait(false) ?? User.Identity?.Name ?? string.Empty;

                universe = await GameCreationService.CreateUniverseWithRootPlaceAsync(
                    connStr,
                    userId,
                    creatorUserName,
                    assetsRoot,
                    starterPlacePath,
                    enableCooldown,
                    _thumbnailService,
                    _configuration,
                    cancellationToken);
            }
            catch
            {
                // If anything fails, fall back to the develop page for now.
                return Redirect("/develop?Page=universes");
            }

            // In real Roblox this would go to /universes/configure?id={universeId}.
            // That endpoint does not exist yet in this clone, so we redirect back
            // to the universes view where the new row can eventually appear once
            // listing is wired up.
            return Redirect("/develop?Page=universes");
        }

        /// <summary>
        /// Returns HTML game cards for the games page. This endpoint is called via AJAX
        /// to load more games dynamically as users scroll or interact with filters.
        /// </summary>
        [HttpGet("moreresultscached")]
        [AllowAnonymous]
        public async Task<IActionResult> MoreResultsCached(
            int SortFilter = 1,
            int TimeFilter = 0,
            int RegionFilter = 183,
            int GenreID = 0,
            int GameFilter = 1,
            int MinBCLevel = 0,
            int StartRows = 0,
            int MaxRows = 14,
            bool IsUserLoggedIn = false,
            int NumberOfRowsToOccupy = 1,
            int NumberOfColumns = 4,
            bool IsInHorizontalScrollMode = false,
            int DeviceTypeId = 1,
            int AdSpan = 0,
            int AdAlignment = 0,
            int v = 2,
            int PersonalizedUniverseId = 0,
            bool useFakeResults = false,
            bool IsGamesThumbnailAsyncEnabled = false,
            CancellationToken cancellationToken = default)
        {
            try
            {
                var connStr = _configuration.GetConnectionString("Default");
                List<GamesQueries.GameEntry> games = new List<GamesQueries.GameEntry>();


                const int maxGamesLimit = 64;
                if (StartRows >= maxGamesLimit)
                {
                    return Content("<div class=\"hidden-item hidden\" id=keyword></div>", "text/html");
                }

                var adjustedMaxRows = Math.Min(MaxRows, maxGamesLimit - StartRows);
                if (adjustedMaxRows <= 0)
                {
                    return Content("<div class=\"hidden-item hidden\" id=keyword></div>", "text/html");
                }

                bool useCache = await _cacheService.IsCacheAvailableAsync(SortFilter, GenreID, cancellationToken);
                
                if (useCache)
                {
                    var cachedGames = await _cacheService.GetCachedGamesAsync(
                        SortFilter, GenreID, StartRows, adjustedMaxRows, cancellationToken);
                    
                    if (cachedGames.Count > 0)
                    {
                        games = GamesCacheService.ToGameEntries(cachedGames);
                    }
                    else
                    {
                        useCache = false;
                    }
                }
                
                if (!useCache)
                {
                    if (GameFilter == 0 && IsUserLoggedIn)
                    {
                        var userIdClaim = User.FindFirst(ClaimTypes.NameIdentifier)?.Value;
                        if (string.IsNullOrWhiteSpace(userIdClaim) || !long.TryParse(userIdClaim, out var userId))
                        {
                            return Content("<div class=\"hidden-item hidden\" id=keyword></div>", "text/html");
                        }

                        games = await GamesQueries.GetUserPublicGamesAsync(
                            userId, SortFilter, StartRows, adjustedMaxRows, GenreID, connStr, cancellationToken);
                    }
                    else
                    {
                        games = await GamesQueries.GetPublicGamesAsync(
                            SortFilter, TimeFilter, GenreID, RegionFilter, 
                            StartRows, adjustedMaxRows, connStr, cancellationToken);
                    }
                }

                var html = BuildGamesHtml(games, StartRows);
                return Content(html, "text/html");
            }
            catch (Exception ex)
            {
                // Log error and return empty result
                Console.WriteLine($"Error loading games: {ex.Message}");
                return Content("<div class=\"hidden-item hidden\" id=keyword></div>", "text/html");
            }
        }

